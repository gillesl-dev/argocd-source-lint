"""Recompute src/argocd_source_lint/unicode_unstable.py.

The code points whose Unicode general category, in one of the supported Python
versions, differs from Go's (tests/fixtures/go_unicode_categories.json, written
by tools/argocd-oracle/regenerate.py). Python 3.11 to 3.14 ship Unicode 14.0 to
16.0 and Go 1.25 Unicode 15.0: outside these code points, Python's
isprintable(), isalpha() and isdecimal() agree with Go's strconv.IsPrint,
unicode.IsLetter and unicode.IsDigit on every supported version.

Needs uv, which installs the Python versions. Run from the repository root:

    uv run python tools/unicode_unstable.py
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATEGORIES = ROOT / "tests" / "fixtures" / "go_unicode_categories.json"
MODULE = ROOT / "src" / "argocd_source_lint" / "unicode_unstable.py"
VERSIONS = ("3.11", "3.12", "3.13", "3.14")

# Run by each Python version: prints the code points whose category differs.
_CHILD = """
import json, sys, unicodedata
ranges = json.load(open(sys.argv[1], encoding="utf-8"))
diff = []
for first, last, category in ranges:
    for code in range(first, last + 1):
        if unicodedata.category(chr(code)) != category:
            diff.append(code)
print(unicodedata.unidata_version)
print(json.dumps(diff))
"""


def _ranges(codes: list[int]) -> list[tuple[int, int]]:
    ranges: list[tuple[int, int]] = []
    for code in sorted(codes):
        if ranges and ranges[-1][1] == code - 1:
            ranges[-1] = (ranges[-1][0], code)
        else:
            ranges.append((code, code))
    return ranges


def main() -> int:
    unstable: set[int] = set()
    versions = []
    for version in VERSIONS:
        result = subprocess.run(
            ["uv", "run", "--no-project", "--python", version, "python", "-I", "-c", _CHILD,
             str(CATEGORIES)],
            capture_output=True, text=True, check=True,
        )  # fmt: skip
        unicode_version, codes = result.stdout.splitlines()
        versions.append(f"Python {version} (Unicode {unicode_version})")
        unstable.update(json.loads(codes))
    ranges = _ranges(sorted(unstable))
    lines = [
        '"""Code points whose Unicode category differs between Go 1.25 and a supported Python.',
        "",
        "Generated by tools/unicode_unstable.py from tests/fixtures/go_unicode_categories.json",
        "and the Unicode tables of:",
        *(f"- {version}" for version in versions),
        "",
        "Do not edit by hand.",
        '"""',
        "",
        "from bisect import bisect_right",
        "",
        "# (first, last) code point ranges, sorted.",
        "UNSTABLE_RANGES: tuple[tuple[int, int], ...] = (",
        *(f"    (0x{first:04X}, 0x{last:04X})," for first, last in ranges),
        ")",
        "_FIRSTS = tuple(first for first, _ in UNSTABLE_RANGES)",
        "",
        "",
        "def is_unstable(char: str) -> bool:",
        '    """Whether Python and Go may disagree on this character\'s category."""',
        "    code = ord(char)",
        "    index = bisect_right(_FIRSTS, code) - 1",
        "    return index >= 0 and code <= UNSTABLE_RANGES[index][1]",
        "",
    ]
    MODULE.write_bytes("\n".join(lines).encode())
    print(
        f"{len(unstable)} code points in {len(ranges)} ranges written to {MODULE.relative_to(ROOT)}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
