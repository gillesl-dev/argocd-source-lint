from __future__ import annotations

import re
from collections import defaultdict
from pathlib import Path

from argocd_source_lint.models import Application, Finding, Severity
from argocd_source_lint.policy import Policy, argocd_instance
from argocd_source_lint.rules.base import Rule

RULE_ID = "duplicate-application-name"

# Kubernetes validates a custom resource's name on create with
# `NameIsDNSSubdomain` (apiextensions-apiserver, customresource/validator.go).
_DNS_SUBDOMAIN = re.compile(r"[a-z0-9]([-a-z0-9]*[a-z0-9])?(\.[a-z0-9]([-a-z0-9]*[a-z0-9])?)*")


def is_dns_subdomain(name: str) -> bool:
    """Return False for a name the API server would reject.

    Such an Application, typically an unfilled template, can never exist,
    so it cannot collide with another one.
    """
    return len(name) <= 253 and _DNS_SUBDOMAIN.fullmatch(name) is not None


class DuplicateApplicationNameRule(Rule):
    """Detect two Applications declared with the same namespace and name.

    Argo CD keys an Application by `(namespace, name)`, so the two manifests
    overwrite each other in the cluster while each looks valid on its own
    (argoproj/argo-cd#9420). The input list already includes
    ApplicationSet-generated Applications.
    """

    rule_id = RULE_ID

    def check(
        self,
        applications: list[Application],
        repo_root: Path,
        policy: Policy,
        local_origin: str | None,
    ) -> list[Finding]:
        severity = policy.rules.get(RULE_ID, Severity.ERROR)
        groups: dict[tuple[str, str, str], list[Application]] = defaultdict(list)

        for app in applications:
            if is_dns_subdomain(app.name):
                instance = argocd_instance(app.source_file, policy.argocd_instances)
                groups[(instance, app.namespace, app.name)].append(app)

        findings = [
            _finding(name, namespace, apps, severity)
            for (_instance, namespace, name), apps in groups.items()
            if len(apps) > 1
        ]
        findings.sort(key=lambda f: f.file.as_posix())
        return findings


def _finding(name: str, namespace: str, apps: list[Application], severity: Severity) -> Finding:
    # Entries generated by one ApplicationSet share its source_file
    # (DESIGN.md), so list each file once.
    files = sorted({app.source_file.as_posix() for app in apps})

    return Finding(
        rule_id=RULE_ID,
        severity=severity,
        application=name,
        message=(
            f"{len(apps)} Applications named `{name}` in namespace `{namespace}` -- "
            "ArgoCD keys an Application by namespace+name, so one silently "
            f"overwrites/fights the other instead of both existing. Declared in: "
            f"{', '.join(files)}."
        ),
        file=Path(files[0]),
    )
